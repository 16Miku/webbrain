const RTL_LOCALES = new Set(['ar', 'fa', 'he']);

export const SELECTION_SHORTCUT_LOCALES = Object.freeze(Object.keys(STRINGS));

export function normalizeSelectionShortcutLocale(value) {
  const requested = String(value || '').trim().toLowerCase();
  if (Object.prototype.hasOwnProperty.call(STRINGS, requested)) return requested;
  const base = requested.split('-')[0];
  return Object.prototype.hasOwnProperty.call(STRINGS, base) ? base : 'en';
}

export function getSelectionShortcutLocalization(value) {
  const locale = normalizeSelectionShortcutLocale(value);
  return {
    locale,
    dir: RTL_LOCALES.has(locale) ? 'rtl' : 'ltr',
    strings: { ...STRINGS.en, ...STRINGS[locale] },
  };
}

export function selectionTranslationLanguageLabel(languageCode, locale) {
  const code = String(languageCode || '').trim().toLowerCase();
  if (!code) return '';
  try {
    return new Intl.DisplayNames([normalizeSelectionShortcutLocale(locale)], { type: 'language' }).of(code) || '';
  } catch {
    return '';
  }
}
