export function normalizeOfflineQueryToken(value) {
  return String(value || '').normalize('NFKC').replace(APOSTROPHE_RE, "'").toLocaleLowerCase('und');
}

export function foldOfflineQueryToken(value) {
  return normalizeOfflineQueryToken(value).normalize('NFKD').replace(/[\u0300-\u036f]/g, '');
}

export function tokenizeOfflineQuery(value) {
  return String(value || '').normalize('NFKC').match(QUERY_TOKEN_RE) || [];
}

function addLanguageStopwords(words, key) {
  const list = LANGUAGE_STOPWORD_SETS[key];
  if (!list) return;
  for (const word of list) words.add(word);
}

export function offlineQueryStopWordsFor(query) {
  const text = String(query || '');
  const words = new Set(OFFLINE_QUERY_STOP_WORDS);
  for (const hint of QUERY_LANGUAGE_HINTS) {
    if (!hint.re.test(text)) continue;
    for (const key of hint.keys) addLanguageStopwords(words, key);
  }
  const tokens = tokenizeOfflineQuery(text).map(token => normalizeOfflineQueryToken(token)).filter(Boolean);
  if (tokens.length) {
    for (const [key, list] of Object.entries(LANGUAGE_STOPWORD_SETS)) {
      let hits = 0;
      for (const token of tokens) {
        if (ENGLISH_OFFLINE_QUERY_STOP_WORDS.has(token)) continue;
        if (list.has(token) || list.has(foldOfflineQueryToken(token))) hits += 1;
        if (hits >= 2) break;
      }
      if (hits >= 2) addLanguageStopwords(words, key);
    }
  }
  return words;
}

export function isOfflineQueryStopWord(value, query = "") {
  const token = normalizeOfflineQueryToken(value);
  if (!token) return false;
  const words = query ? offlineQueryStopWordsFor(query) : OFFLINE_QUERY_STOP_WORDS;
  if (words.has(token)) return true;
  const folded = foldOfflineQueryToken(token);
  return folded !== token && words.has(folded);
}

