export function getOfflineAnswerCopy(locale = 'en') {
  const code = String(locale || 'en').trim().slice(0, 2).toLowerCase();
  return { ...ENGLISH_OFFLINE_ANSWER_COPY, ...(OFFLINE_ANSWER_TRANSLATIONS[code] || {}) };
}

export function offlineAnswerText(locale, key) {
  const code = String(locale || 'en').trim().slice(0, 2).toLowerCase();
  const translated = OFFLINE_ANSWER_TRANSLATIONS[code]?.[key];
  return translated || ENGLISH_OFFLINE_ANSWER_COPY[key] || '';
}

