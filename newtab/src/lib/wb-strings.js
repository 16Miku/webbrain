/** Look up a "wb.*" key in the WebBrain UI language, falling back to English. */
export function wbT(key, locale = resolveWebBrainLocale()) {
  return WB_STRINGS[locale]?.[key] ?? WB_STRINGS.en[key] ?? key;
}

export const isWbKey = (key) => typeof key === 'string' && key.startsWith('wb.');
